import re,sys
src=open(sys.argv[1]).read()
def arr(name):
    m=re.search(name+r' = new String\[\]\{(.*?)\};',src,re.S)
    return [s.strip() for s in re.findall(r'"(.*?)"',m.group(1))]
def hz(s):
    if s.lower().startswith('off'): return -1.0
    return float(s[:-1])*1000 if s.endswith('k') else float(s)
def ratio(s):
    if s=='Off': return 1.0
    if s.startswith('Inf'): return 1e9
    return float(s.split(':')[0])
def tempo(s):
    if s=='Ignored': return 0.0
    if s=='1': return 1.0
    m=re.match(r'1/(\d+)([DT]?)',s); f=1.0/int(m.group(1))
    return f*1.5 if m.group(2)=='D' else (f*2/3 if m.group(2)=='T' else f)
def fmt(v):
    if abs(v)>=1e8: return '1e9f'
    t='%.6g'%v
    return (t if ('.' in t or 'e' in t) else t+'.0')+'f'
spec=[('compTime','COMP_TIME_VALUES',float,3),('compRatio','COMP_RATIO_VALUES',ratio,0),
('tapTempo','TAP_TEMPO_VALUES',tempo,0),('speed','SPEED_VALUES',float,0),('hiCut','HI_CUT_VALUES',hz,0),
('loCut','LO_CUT_VALUES',hz,0),('eqWidth','EQ_WIDTH_VALUES',float,3),('eqFreq','EQ_FREQ_VALUES',hz,25),
('reverbSize','REVERB_SIZE_VALUES',None,0),('reverbHiColor','REVERB_HI_COLOR_VALUES',None,0),('reverbLoColor','REVERB_LO_COLOR_VALUES',None,0)]
o=['// GENERATED by scripts/gen_tables.py from the GLydian value tables (DiscretRange.java). Do not edit.',
'#include "gmr/Tables.h"','#include <cstring>','#include <algorithm>','namespace gmr {','namespace {']
for n,j,f,off in spec:
    a=arr(j)
    vals=[f(x) if f else float(i) for i,x in enumerate(a)]
    o.append('const char* const %sL[] = {%s};'%(n,', '.join('"%s"'%x for x in a)))
    o.append('const float %sV[] = {%s};'%(n,', '.join(fmt(v) for v in vals)))
    sys.stderr.write('%s %d entries\n'%(n,len(a)))
o.append('} // namespace'); o.append('namespace tables {')
for n,j,f,off in spec:
    o.append('const ValueTable %s { %sL, %sV, (int)(sizeof(%sV)/sizeof(float)), %d };'%(n,n,n,n,off))
o.append('} // namespace tables')
o.append('''
float tableValue(const ValueTable& t, int stored) noexcept {
    int i = std::clamp(stored - t.storeOffset, 0, t.size - 1);
    return t.values[i];
}
const char* tableLabel(const ValueTable& t, int stored) noexcept {
    int i = std::clamp(stored - t.storeOffset, 0, t.size - 1);
    return t.labels[i];
}
int tableStoredForLabel(const ValueTable& t, const char* label) noexcept {
    for (int i = 0; i < t.size; ++i)
        if (std::strcmp(t.labels[i], label) == 0) return i + t.storeOffset;
    return -1;
}
} // namespace gmr''')
open(sys.argv[2],'w').write('\n'.join(o)+'\n')
