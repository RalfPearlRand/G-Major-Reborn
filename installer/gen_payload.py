"""Scan a staging dir and emit payload.rc / payload.h for Installer.cpp.
Layout: <stage>/app/... -> install folder, <stage>/vst3/... -> Common Files\\VST3, <stage>/userpresets/... -> Documents\\G-Major Reborn"""
import os, sys
stage, outdir, version, icon, manifest = sys.argv[1:6]
roots = [("app", 0), ("vst3", 1), ("userpresets", 2)]
entries = []
for name, root in roots:
    base = os.path.join(stage, name)
    for dp, _, files in os.walk(base):
        for f in sorted(files):
            full = os.path.join(dp, f)
            entries.append((root, os.path.relpath(full, base).replace("/", "\\"), full, os.path.getsize(full)))
def cstr(s): return s.replace("\\", "\\\\").replace('"', '\\"')
with open(os.path.join(outdir, "payload.rc"), "w", encoding="utf-8") as rc:
    rc.write('#pragma code_page(65001)\n1 ICON "%s"\n1 24 "%s"\n' % (cstr(icon), cstr(manifest)))
    v = [int(x) for x in version.split(".")] + [0] * 4
    rc.write('1 VERSIONINFO FILEVERSION %d,%d,%d,0 PRODUCTVERSION %d,%d,%d,0\nBEGIN BLOCK "StringFileInfo" BEGIN BLOCK "041604B0" BEGIN\n'
             ' VALUE "CompanyName", "GMR Project"\n VALUE "FileDescription", "G-Major Reborn Setup"\n VALUE "FileVersion", "%s"\n'
             ' VALUE "ProductName", "G-Major Reborn"\n VALUE "ProductVersion", "%s"\n VALUE "LegalCopyright", "GPL-3.0-or-later"\n'
             'END END BLOCK "VarFileInfo" BEGIN VALUE "Translation", 0x416, 1200 END END\n' % (v[0], v[1], v[2], v[0], v[1], v[2], version, version))
    for i, (_, _, full, _) in enumerate(entries):
        rc.write('%d RCDATA "%s"\n' % (1000 + i, cstr(full)))
with open(os.path.join(outdir, "payload.h"), "w", encoding="utf-8") as h:
    h.write("// generated by installer/gen_payload.py\n#pragma once\nstruct PayloadEntry { int id; const wchar_t* rel; int root; unsigned long long size; };\n")
    h.write('static const wchar_t kVersion[] = L"%s";\nstatic const PayloadEntry kPayload[] = {\n' % version)
    for i, (root, rel, _, size) in enumerate(entries):
        h.write('    { %d, L"%s", %d, %dull },\n' % (1000 + i, cstr(rel), root, size))
    h.write("};\nstatic const int kPayloadCount = %d;\nstatic const unsigned long long kTotalBytes = %dull;\n" % (len(entries), sum(e[3] for e in entries)))
print("%d files, %.1f MB" % (len(entries), sum(e[3] for e in entries) / 1e6))
